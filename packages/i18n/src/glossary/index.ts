export function translateMedicalTerm(
  term: string,
  locale: SupportedLocale,
  fallbackLocale: SupportedLocale = "en"
): string {
  const entry = MEDICAL_GLOSSARY[term];
  if (!entry) return term;
  return entry[locale] || entry[fallbackLocale] || term;
}

export function getMedicalGlossaryForLocale(locale: SupportedLocale): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [term, translations] of Object.entries(MEDICAL_GLOSSARY)) {
    result[term] = translations[locale] || translations.en || term;
  }
  return result;
}

export function hasMedicalTranslation(term: string, locale: SupportedLocale): boolean {
  const entry = MEDICAL_GLOSSARY[term];
  return !!entry?.[locale];
}

export function getMissingMedicalTranslations(locale: SupportedLocale): string[] {
  const missing: string[] = [];
  for (const [term, translations] of Object.entries(MEDICAL_GLOSSARY)) {
    if (!translations[locale]) {
      missing.push(term);
    }
  }
  return missing;
}