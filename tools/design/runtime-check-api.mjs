#!/usr/bin/env node
/**
 * Runtime check for the APP screens of a batch (QUALITY_STANDARDS.md §7.3).
 *
 * The native app cannot be driven from CI, so each screen's endpoint list (inventory/screens.json, the same
 * list WIRING_REPORT.md is built from) is exercised against the seeded backend with the three sessions the
 * app can have: seeded patient, guest (what a first launch has) and none. GET calls are executed; every
 * other method is listed as "not executed" (it would change data) except POST /auth/guest, which only
 * creates the guest session. Paths with a `:param` are not executed (no real id to use) and are listed too.
 *
 *   node tools/design/runtime-check-api.mjs --api http://localhost:3002/api/v1 --batch 0
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : d; };
const API = arg('api', 'http://localhost:3002/api/v1');
const BATCH = arg('batch', '0');
const IDENTIFIER = arg('identifier', '+966509999999');
const PASSWORD = arg('password', 'Test@123');
const OUT = resolve(REPO, arg('out', `docs/design/audit/runtime-batch-${BATCH}-app.md`));

const shape = (t) => {
  try {
    const j = JSON.parse(t);
    if (Array.isArray(j)) return `array(${j.length})`;
    if (j && typeof j === 'object') {
      const keys = Object.keys(j);
      const lens = keys.filter((k) => Array.isArray(j[k])).map((k) => `${k}[${j[k].length}]`);
      return `{${keys.slice(0, 6).join(',')}${keys.length > 6 ? ',…' : ''}}${lens.length ? ' ' + lens.join(' ') : ''}`;
    }
    return typeof j;
  } catch { return 'non-json'; }
};
const post = async (path, body) => (await fetch(`${API}${path}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();
const patient = (await post('/auth/login', { identifier: IDENTIFIER, password: PASSWORD })).token?.accessToken;
const guest = (await post('/auth/guest', {}).catch(() => ({}))); const guestToken = guest.token?.accessToken ?? guest.accessToken;
if (!patient) throw new Error('seeded patient login failed');

const routes = JSON.parse(readFileSync(join(REPO, 'docs/design/inventory/screens.json'), 'utf8')).routes
  .filter((r) => r.app === 'patient-app' && String(r.batch) === String(BATCH));

const sessions = [['patient', patient], ['guest', guestToken], ['none', null]];
let md = `# Runtime check, Batch ${BATCH} (patient-app endpoints)\n\nGenerated by \`node tools/design/runtime-check-api.mjs\` against ${API}. Seeded patient \`${IDENTIFIER}\`; GET calls executed with each session (patient / guest / none); mutations not executed.\n\n`;
const fails = [];
const seen = new Set();
for (const r of routes) {
  const calls = (r.calls ?? []).filter((c) => c.target === 'backend');
  if (!calls.length) { md += `## \`${r.route}\`\nNo API call (static screen).\n\n`; continue; }
  md += `## \`${r.route}\`\n\n| Call | Patient | Guest | None |\n|---|---|---|---|\n`;
  for (const c of calls) {
    const key = `${c.method} ${c.path}${c.query ? '?' : ''}`;
    if (c.method !== 'GET') { md += `| ${c.method} \`${c.path}\` | not executed (mutation) | | |\n`; continue; }
    if (c.path.includes(':')) { md += `| GET \`${c.path}\` | not executed (needs a real id) | | |\n`; continue; }
    const row = [];
    for (const [name, tok] of sessions) {
      const res = await fetch(`${API}${c.path}${c.query ? '?q=a' : ''}`, { headers: tok ? { authorization: `Bearer ${tok}` } : {} });
      const body = await res.text();
      row.push(`${res.status} ${shape(body)}`);
      if (name === 'patient' && !seen.has(key) && res.status >= 400) fails.push(`${r.route} GET ${c.path} → ${res.status} (patient)`);
    }
    seen.add(key);
    md += `| GET \`${c.path}\` | ${row.join(' | ')} |\n`;
  }
  md += '\n';
}
md += `## Failures with the seeded patient session\n\n${fails.length ? fails.map((f) => `- ${f}`).join('\n') : 'None.'}\n`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md, 'utf8');
console.log(`runtime-check-api: ${routes.length} route(s), ${fails.length} failure(s) -> ${OUT}`);
