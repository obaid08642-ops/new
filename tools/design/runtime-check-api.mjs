#!/usr/bin/env node
/**
 * Runtime check for the APP screens of a batch (QUALITY_STANDARDS.md §7.3).
 *
 * The native app cannot be driven from CI, so each screen's endpoint list (inventory/screens.json, the same
 * list WIRING_REPORT.md is built from) is exercised against the seeded backend with the three sessions the
 * app can have: seeded patient, guest (what a first launch has) and none. GET calls are executed; every
 * other method is listed as "not executed" (it would change data) except POST /auth/guest, which only
 * creates the guest session. Paths with a `:param` are not executed (no real id to use) and are listed too.
 *
 *   node tools/design/runtime-check-api.mjs --api http://localhost:3002/api/v1 --batch 0
 *
 * Provider app (read-only audit):  node tools/design/runtime-check-api.mjs --app provider [--api ...] [--email E --password P]
 *   Endpoints come from docs/design/inventory/provider-screens.json, grouped by area, one report per area:
 *   docs/design/audit/runtime-provider-<area>.md. A provider can only sign in with a provider_accounts row (POST /provider/auth/login
 *   takes an email); the test seeds create users + profiles only, so unless --email/--password (or PROVIDER_EMAIL/PROVIDER_PASSWORD)
 *   sign in, the GET calls run with the seeded PATIENT session (expects 403 = route exists and is role-guarded) and with no session
 *   (expects 401); a 404 is a missing route, a 5xx a failure. Calls that need a provider session are listed as "not executed as provider".
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : d; };
const API = arg('api', 'http://localhost:3002/api/v1');
const BATCH = arg('batch', '0');
const APP = arg('app', 'patient');
const IDENTIFIER = arg('identifier', '+966509999999');
const PASSWORD = arg('password', 'Test@123');
const OUT = resolve(REPO, arg('out', `docs/design/audit/runtime-batch-${BATCH}-app.md`));

const shape = (t) => {
  try {
    const j = JSON.parse(t);
    if (Array.isArray(j)) return `array(${j.length})`;
    if (j && typeof j === 'object') {
      const keys = Object.keys(j);
      const lens = keys.filter((k) => Array.isArray(j[k])).map((k) => `${k}[${j[k].length}]`);
      return `{${keys.slice(0, 6).join(',')}${keys.length > 6 ? ',…' : ''}}${lens.length ? ' ' + lens.join(' ') : ''}`;
    }
    return typeof j;
  } catch { return 'non-json'; }
};
const post = async (path, body) => (await fetch(`${API}${path}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();
if (APP === 'provider') {
  const email = arg('email', process.env.PROVIDER_EMAIL);
  const pass = arg('password', process.env.PROVIDER_PASSWORD);
  let providerToken = null;
  let loginNote = 'no provider credentials given (the seeds create no provider_accounts row, see the header of this tool)';
  if (email && pass) {
    const r = await fetch(`${API}/provider/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email, password: pass }) });
    const j = await r.json().catch(() => ({}));
    providerToken = j.access_token ?? null;
    loginNote = providerToken ? `signed in as provider ${email} (${j.provider_type ?? '?'})` : `provider sign-in failed for ${email}: HTTP ${r.status}`;
  }
  const pj = await post('/auth/login', { identifier: IDENTIFIER, password: PASSWORD }).catch(() => ({}));
  const patientToken = pj.token?.accessToken ?? null;
  const all = JSON.parse(readFileSync(join(REPO, 'docs/design/inventory/provider-screens.json'), 'utf8')).routes;
  const sess = [['provider', providerToken], ['patient', patientToken], ['none', null]];
  const code = (x) => Number(String(x).split(' ')[0]);
  const summary = [];
  const findings = [];
  for (const area of [...new Set(all.map((r) => r.area))]) {
    let out = `# Runtime check, provider-app, area ${area}\n\nGenerated by \`node tools/design/runtime-check-api.mjs --app provider\` against ${API}. ${loginNote}. Seeded patient \`${IDENTIFIER}\` is used to prove role guarding. GET calls only; mutations and \`:param\` paths are not executed.\n\n`;
    const seenCalls = new Map();
    let n = 0, unexpected = 0, notAsProvider = 0;
    for (const r of all.filter((x) => x.area === area)) {
      const calls = (r.calls ?? []).filter((c) => c.target === 'backend');
      out += `## \`${r.route}\`\n\n`;
      if (!calls.length) { out += 'No API call.\n\n'; continue; }
      out += '| Call | Provider | Patient | None | Verdict |\n|---|---|---|---|---|\n';
      for (const c of calls) {
        if (c.method !== 'GET') { out += `| ${c.method} \`${c.path}\` | not executed (mutation) | | | |\n`; continue; }
        if (c.path.includes(':')) { out += `| GET \`${c.path}\` | not executed (needs a real id) | | | |\n`; continue; }
        const k = c.path;
        if (!seenCalls.has(k)) {
          const row = [];
          for (const [who, tok] of sess) {
            if (who === 'provider' && !tok) { row.push('not executed (no provider session)'); continue; }
            const res = await fetch(`${API}${c.path}`, { headers: tok ? { authorization: `Bearer ${tok}` } : {} });
            row.push(`${res.status} ${shape(await res.text())}`);
          }
                    const providerLike = /^\/(provider\/|pharmacy\/(inventory|returns\/provider|orders|chat)|emergency\/driver|insurance\/requests\/provider|calls\/provider|radiology\/|labs?\/(orders|provider)|home-care\/(jobs|provider-))/.test(c.path);
          const [pr, pa, no] = row.map(code);
          const verdict = row.some((x) => code(x) >= 500) ? 'FAIL 5xx'
            : providerToken ? (pr >= 400 ? `FAIL provider ${pr}` : 'ok')
            : no === 200 ? 'public (no session needed)'
            : pa === 200 && providerLike ? 'REVIEW: provider endpoint answers a PATIENT session with 200 (role guard?)'
            : pa === 200 ? 'any signed-in user (ok)'
            : pa === 404 ? 'patient session gets 404: needs a provider / onboarding identity to judge'
            : (pa === 403 || pa === 401) && no === 401 ? 'route exists, guarded; not executed as provider'
            : 'check';
          seenCalls.set(k, { row, verdict });
          if (/^(REVIEW|FAIL|patient session gets 404|check)/.test(verdict)) findings.push({ area, path: c.path, screens: all.filter((x) => x.area === area && x.calls.some((y) => y.method === 'GET' && y.path === c.path)).map((x) => x.route), patient: row[1], none: row[2], verdict });
        }
        const v = seenCalls.get(k);
        n++;
        if (/^(FAIL|check|REVIEW|patient session gets 404)/.test(v.verdict)) unexpected++;
        if (/not executed as provider/.test(v.verdict)) notAsProvider++;
        out += `| GET \`${c.path}\` | ${v.row.join(' | ')} | ${v.verdict} |\n`;
      }
      out += '\n';
    }
    out += `## Summary\n\n${n} GET call(s) listed, ${unexpected} unexpected, ${notAsProvider} not executed as provider.\n`;
    const file = resolve(REPO, `docs/design/audit/runtime-provider-${area}.md`);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, out, 'utf8');
    summary.push(`${area}: ${n} GET, ${unexpected} unexpected, ${notAsProvider} guarded-only`);
  }
  writeFileSync(resolve(REPO, 'docs/design/inventory/provider-runtime.json'), JSON.stringify({ login: loginNote, findings }, null, 1) + '\n');
  console.log(`runtime-check-api (provider): ${loginNote}\n${summary.join('\n')}`);
  process.exit(0);
}
const patient = (await post('/auth/login', { identifier: IDENTIFIER, password: PASSWORD })).token?.accessToken;
const guest = (await post('/auth/guest', {}).catch(() => ({}))); const guestToken = guest.token?.accessToken ?? guest.accessToken;
if (!patient) throw new Error('seeded patient login failed');

const routes = JSON.parse(readFileSync(join(REPO, 'docs/design/inventory/screens.json'), 'utf8')).routes
  .filter((r) => r.app === 'patient-app' && String(r.batch) === String(BATCH));

const sessions = [['patient', patient], ['guest', guestToken], ['none', null]];
let md = `# Runtime check, Batch ${BATCH} (patient-app endpoints)\n\nGenerated by \`node tools/design/runtime-check-api.mjs\` against ${API}. Seeded patient \`${IDENTIFIER}\`; GET calls executed with each session (patient / guest / none); mutations not executed.\n\n`;
const fails = [];
const seen = new Set();
for (const r of routes) {
  const calls = (r.calls ?? []).filter((c) => c.target === 'backend');
  if (!calls.length) { md += `## \`${r.route}\`\nNo API call (static screen).\n\n`; continue; }
  md += `## \`${r.route}\`\n\n| Call | Patient | Guest | None |\n|---|---|---|---|\n`;
  for (const c of calls) {
    const key = `${c.method} ${c.path}${c.query ? '?' : ''}`;
    if (c.method !== 'GET') { md += `| ${c.method} \`${c.path}\` | not executed (mutation) | | |\n`; continue; }
    if (c.path.includes(':')) { md += `| GET \`${c.path}\` | not executed (needs a real id) | | |\n`; continue; }
    const row = [];
    for (const [name, tok] of sessions) {
      const res = await fetch(`${API}${c.path}${c.query ? '?q=a' : ''}`, { headers: tok ? { authorization: `Bearer ${tok}` } : {} });
      const body = await res.text();
      row.push(`${res.status} ${shape(body)}`);
      if (name === 'patient' && !seen.has(key) && res.status >= 400) fails.push(`${r.route} GET ${c.path} → ${res.status} (patient)`);
    }
    seen.add(key);
    md += `| GET \`${c.path}\` | ${row.join(' | ')} |\n`;
  }
  md += '\n';
}
md += `## Failures with the seeded patient session\n\n${fails.length ? fails.map((f) => `- ${f}`).join('\n') : 'None.'}\n`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, md, 'utf8');
console.log(`runtime-check-api: ${routes.length} route(s), ${fails.length} failure(s) -> ${OUT}`);
