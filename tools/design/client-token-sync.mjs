#!/usr/bin/env node
/**
 * Client token sync gate (12.A0 / 12.A2).
 *
 * packages/design-tokens is the single source of truth. A client that keeps its
 * own copy of the palette is a second source of truth, and the copies drift.
 *
 * This is not hypothetical. provider-app/src/theme/tokens.ts said, in its own
 * header comment, that it was a "MIRROR of packages/design-tokens/tokens.json"
 * — and it held `primary: '#B8E030'`, `mint: '#5FD9B3'`, `navy: '#1E332E'`,
 * the pre-A2 palette, while the owner approved coral. Ten screens imported it.
 *
 * Nothing caught it, and the reason matters: the token contrast check reads
 * tokens.json, and the runtime contrast check renders patient-web. This file sat
 * in the gap between the two gates, being checked by neither. A guard has to
 * cover the thing, not the thing's neighbours.
 *
 * So for every client this walks the source and asserts that any colour literal
 * it hard-codes is one the token file also declares, and that no client carries
 * a colour that tokens.json does not contain. Colours that legitimately differ
 * (a generated mirror, an asset) are declared in EXEMPT below with a reason.
 *
 * Usage: node tools/design/client-token-sync.mjs
 */

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { resolve, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..');

const argv = process.argv.slice(2);
const IS_UPDATE = argv.includes('--update');
const BASELINE_PATH = join(REPO, 'tools/design/client-token-sync.baseline.json');

const tokensPath = join(REPO, 'packages/design-tokens/tokens.json');
const tokensRaw = readFileSync(tokensPath, 'utf8');

/** Every colour literal the token file itself declares. */
const declared = new Set(
  [...tokensRaw.matchAll(/#[0-9a-fA-F]{3,8}\b|\brgba?\([^)]*\)/g)].map((m) =>
    m[0].toUpperCase().replace(/\s+/g, ''),
  ),
);

const CLIENTS = [
  { name: 'provider-app', root: 'provider-app/src' },
  { name: 'patient-app', root: 'patient-app/src' },
  { name: 'admin', root: 'admin/src' },
];

/** Paths allowed to hold colours that are not in tokens.json, each with a reason. */
const EXEMPT = [
  {
    prefix: 'provider-app/src/theme/tokens.generated.ts',
    reason:
      'GENERATED by tools/design/sync-client-tokens.mjs from tokens.json and committed; ' +
      '`--check` fails if it drifts, so the literals in it ARE the token file',
  },
];

const SKIP_DIRS = new Set(['node_modules', '.next', 'dist', 'build', 'coverage', '__snapshots__']);
const SOURCE_EXT = new Set(['.ts', '.tsx', '.js', '.jsx']);

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (SOURCE_EXT.has(full.slice(full.lastIndexOf('.')))) out.push(full);
  }
  return out;
}

const exemptReason = (rel) => EXEMPT.find((e) => rel === e.prefix || rel.startsWith(e.prefix));

// Baseline: per-FILE counts, so a file that is cleaned up cannot hide a new
// violation behind the slack it left. Same rule as no-raw-color: --update only
// ever lowers, and a file that has grown is refused.
// Always READ the baseline. --update controls writing, not reading: if it did
// not read, there would be nothing to compare a new violation against and it
// would record one instead of refusing, which is the one thing a ratchet must
// never do.
const baseline = existsSync(BASELINE_PATH)
  ? JSON.parse(readFileSync(BASELINE_PATH, 'utf8'))
  : null;

let failures = 0;
const report = [];
const perFile = {};

for (const client of CLIENTS) {
  const root = join(REPO, client.root);
  if (!existsSync(root)) {
    console.error(`client-token-sync: ${client.root} does not exist.`);
    process.exit(2);
  }
  const files = walk(root);
  const offenders = [];
  let exemptCount = 0;

  for (const file of files) {
    const rel = relative(REPO, file);
    if (exemptReason(rel)) {
      exemptCount++;
      continue;
    }
    const src = readFileSync(file, 'utf8');
    // Strip comments so documentation about a colour is not a violation.
    const code = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
    const lines = code.split('\n');
    lines.forEach((line, i) => {
      for (const m of line.matchAll(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|\brgba?\([^)]*\)/g)) {
        // `rgba(${r}, ${g}, ${b}, ${alpha})` is a template that COMPUTES a colour,
        // not one that chooses it. Only the literal prefix before an
        // interpolation is a hard-coded value, and `rgba(` alone is not a colour.
        if (/\$\{/.test(m[0])) continue;
        const norm = m[0].toUpperCase().replace(/\s+/g, '');
        if (declared.has(norm)) continue;
        offenders.push({ line: i + 1, text: m[0], file: rel });
      }
    });
  }

  const byFile = new Map();
  for (const o of offenders) {
    if (!byFile.has(o.file)) byFile.set(o.file, []);
    byFile.get(o.file).push(o);
  }

  for (const [file, list] of byFile) perFile[file] = list.length;
  report.push({ client: client.name, files: files.length, exempt: exemptCount, offenders: byFile });

  // With no baseline yet this is the first record, so there is nothing to have
  // grown past. With a baseline, a file that has more off-palette colours than
  // it is allowed is a NEW violation and must be reported, not absorbed.
  const newFiles = baseline
    ? [...byFile].filter(([file]) => (baseline.files[file] ?? 0) < byFile.get(file).length)
    : [];
  if (newFiles.length) {
    console.error(`\n${client.name}: ${newFiles.length} file(s) have MORE off-palette colours than allowed:`);
    newFiles.forEach(([file, list]) =>
      console.error(`  ${file}: ${list.length} (baseline allows ${baseline.files[file] ?? 0})`));
  }

  // Detail is printed only for NEW violations. Ratcheted debt is summarised in
  // the table below, not re-listed on every run — a wall of known debt trains
  // people to ignore the output.
  if (newFiles.length) {
    failures += newFiles.length;
    for (const [file, list] of newFiles) {
      console.error(`\nNEW  ${file}: ${list.length} off-palette colour(s), baseline allows ${baseline.files[file] ?? 0}`);
      list.slice(0, 5).forEach((o) => console.error(`      line ${o.line}: ${o.text}`));
      if (list.length > 5) console.error(`      ... +${list.length - 5} more`);
    }
  }
}

console.log(`client-token-sync: tokens.json declares ${declared.size} colour value(s).`);
console.log('');
for (const r of report) {
  const count = [...r.offenders.values()].reduce((a, l) => a + l.length, 0);
  console.log(
    `  ok   ${r.client.padEnd(13)} ${String(r.files).padStart(4)} source file(s), ` +
      `${r.exempt} generated, ${r.offenders.size} file(s) / ${count} colour(s) ratcheted`,
  );
}

if (IS_UPDATE) {
  // Same contract as no-raw-color: --update lowers counts, it never raises one.
  // Without this check it would happily record a NEW violation into the
  // baseline and launder it, which is the one thing a ratchet must not do.
  if (failures) {
    console.error('client-token-sync: --update refused. The files listed above have MORE');
    console.error('off-palette colours than the baseline allows. Fix them first; --update lowers only.');
    process.exit(1);
  }
  writeFileSync(BASELINE_PATH, JSON.stringify({
    note:
      'Client files carrying colour literals that tokens.json does not declare, per file. ' +
      '--update only ever lowers a count. 12.A11 clears these as screens are rebuilt.',
    files: perFile,
  }, null, 2) + '\n', 'utf8');
  const total = Object.values(perFile).reduce((a, b) => a + b, 0);
  console.log(
    `client-token-sync: recorded ${Object.keys(perFile).length} file(s), ${total} off-palette colour(s). ` +
      `PARTIAL: the debt is measured, not cleared. 12.A11 clears it.`,
  );
  process.exit(0);
}

if (!baseline) {
  console.error('client-token-sync: no baseline. Run --update once to record the current debt.');
  process.exit(2);
}
const baseTotal = Object.values(baseline.files).reduce((a, b) => a + b, 0);
const nowTotal = Object.values(perFile).reduce((a, b) => a + b, 0);
const gone = Object.keys(baseline.files).filter((f) => !(f in perFile));
if (gone.length) {
  console.error(`\n  ${gone.length} file(s) are now clean but still in the baseline — run --update to lower it`);
}
if (failures || gone.length) {
  console.error(
    `\nclient-token-sync: FAILED. No NEW off-palette colour is allowed; ${nowTotal} remain (baseline ${baseTotal}).`,
  );
  process.exit(1);
}
console.log(
  `client-token-sync: no NEW off-palette colour. ${nowTotal} remain (baseline ${baseTotal}). ` +
    `PARTIAL: 12.A11 clears them.`,
);
