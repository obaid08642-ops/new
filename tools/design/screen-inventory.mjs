#!/usr/bin/env node
/**
 * 12.C3 — the screen inventory, generated.
 *
 * patient-web alone has 270 `page.tsx` routes. Writing 270 audit entries by hand
 * would produce exactly what §C4 warns against: a number presented as verified
 * because it is written down. So the inventory is derived from the route tree,
 * which cannot drift from the app, and the per-screen *audit* is a separate,
 * opt-in document.
 *
 *   node tools/design/screen-inventory.mjs           # write docs/audit/screens/inventory.md
 *   node tools/design/screen-inventory.mjs --check   # fail if the committed inventory is stale
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { resolve, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(REPO, 'docs/audit/screens/inventory.md');
const CHECK = process.argv.includes('--check');

const CLIENTS = [
  { name: 'patient-web', root: 'patient-web/app/[locale]', port: 'web' },
  { name: 'patient-app', root: 'patient-app/app', port: 'native' },
  { name: 'admin', root: 'admin/src/pages', port: 'web' },
  { name: 'provider-app', root: 'provider-app/src/screens', port: 'native' },
];

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const lines = [];
const problems = [];
let audited = 0;

for (const c of CLIENTS) {
  const base = join(REPO, c.root);
  // `slice` leaves the leading separator, so the first version compared
  // `/medicines/page.tsx === 'page.tsx'` and matched nothing: patient-web and
  // admin both reported ZERO screens while 310 of them existed. A generator that
  // under-reports is worse than none, because its output reads as fact — this
  // file would have said "0 screens" and been believed.
  const files = walk(base).filter((f) => {
    const n = f.slice(base.length).replace(/^\//, '');
    return c.port === 'web'
      ? n === 'page.tsx' || n.endsWith('/page.tsx') || (n.startsWith('api/') && n.endsWith('.ts'))
      : f.endsWith('.tsx');
  });
  if (files.length === 0) problems.push(`${c.name}: the route walk found no screens — the filter, not the app, is at fault.`);

  const screens = [];
  for (const f of files) {
    let rel = relative(base, f).replace(/\\/g, '/');
    if (c.port === 'web') {
      if (rel === 'page.tsx') rel = '/';
      else if (rel.startsWith('api/')) rel = '/api/' + rel.slice(4).replace(/\.ts$/, '');
      else rel = rel.replace(/\/?page\.tsx$/, '');
    } else {
      rel = rel.replace(/\.tsx$/, '').replace(/\/?index$/, '') || '/';
    }
    const src = readFileSync(f, 'utf8');
    screens.push({
      rel: rel === '' ? '/' : rel,
      lines: src.split('\n').length,
      // Audited = it has its own document under docs/audit/screens/<client>-*.md
      hasDoc: existsSync(join(REPO, 'docs/audit/screens', `${c.name}${rel.replace(/\//g, '-')}.md`)),
      // Signals worth a human's attention, recorded not judged.
      client: /\buse client\b/.test(src),
      dynamic: /\bdynamic\s*\(/.test(src) || /"use client"/.test(src),
      rawColour: (src.match(/#[0-9a-f]{3,8}\b|\brgba?\(/gi) || []).length,
      lucide: /from ["']lucide-react["']/.test(src),
    });
  }
  screens.sort((a, b) => a.rel.localeCompare(b.rel));
  const docd = screens.filter((s) => s.hasDoc).length;
  audited += docd;

  lines.push(`## ${c.name} — ${screens.length} screen(s), ${docd} documented`);
  lines.push('');
  lines.push('| screen | own doc | use client | raw colour | lucide | src lines |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const s of screens) {
    lines.push(
      `| \`${s.rel}\` | ${s.hasDoc ? 'yes' : '—'} | ${s.client ? 'y' : ''} | ${s.rawColour} | ${s.lucide ? '**y**' : ''} | ${s.lines} |`,
    );
  }
  lines.push('');
}

const header = `# Screen inventory — 12.C3 (GENERATED)

<!-- GENERATED by tools/design/screen-inventory.mjs — do not edit by hand. -->
<!-- Run \`node tools/design/screen-inventory.mjs --check\` to prove it still matches the route tree. -->

The full screen-by-screen audit lives in \`docs/audit/screens/<client>-<route>.md\`,
one file per screen. This file is the index and the coverage count, and it is
generated so the two cannot disagree: the moment a route is added, this file goes
stale and the check fails.

\`.hasDoc\` is a plain existence test against the filename convention above. It is
not a judgement that the document is any good — it is the weakest possible claim,
and it is the only one this file makes.

`;

const next = header + lines.join('\n');

if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== next) {
    console.error('screen-inventory: FAILED — the inventory is stale. Run the generator.');
    process.exit(1);
  }
  console.log('screen-inventory: up to date.');
} else {
  writeFileSync(OUT, next, 'utf8');
  console.log(`screen-inventory: wrote ${OUT} (${audited} screen(s) with their own audit document).`);
}
