#!/usr/bin/env node
/**
 * Extract the REGULAR-weight outlines of the curated line icons (packages/ui/icons/names.ts) from
 * `@phosphor-icons/react` into packages/ui/icons/line.ts.
 *
 * WHY: `import * as phosphor from '@phosphor-icons/react'` ships every weight of every glyph the set
 * uses (thin, light, regular, bold, fill, duotone: six outlines per icon) although `<Icon>` only ever draws
 * `regular`. The 32 glyphs cost about 29 KB gz of shared JS on every page (issue #286). The regular outline
 * is one `path`, so the data is 11 KB raw (about 4 KB gz) and `<Icon>` draws it itself: same geometry, same
 * `viewBox`, same attributes, no icon library at runtime.
 *
 * Usage: node tools/design/extract-line-icons.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');
const OUT = join(REPO, 'packages/ui/icons/line.ts');

const names = readFileSync(join(REPO, 'packages/ui/icons/names.ts'), 'utf8');
const block = names.match(/LINE_ICON_COMPONENTS\s*=\s*\{([\s\S]*?)\}\s*as const/);
if (!block) throw new Error('extract-line-icons: LINE_ICON_COMPONENTS not found in packages/ui/icons/names.ts');
const entries = [...block[1].matchAll(/(?:'([^']+)'|(\w+))\s*:\s*'(\w+)'/g)].map((m) => [m[1] ?? m[2], m[3]]);
if (!entries.length) throw new Error('extract-line-icons: no entries parsed');

const defsDir = ['patient-web', 'packages/ui', 'admin']
  .map((d) => join(REPO, d, 'node_modules/@phosphor-icons/react/dist/defs'))
  .find((d) => existsSync(d));
if (!defsDir) throw new Error('extract-line-icons: @phosphor-icons/react is not installed (run pnpm install in patient-web)');

const lines = [];
for (const [name, component] of entries) {
  const src = readFileSync(join(defsDir, `${component}.es.js`), 'utf8');
  const start = src.indexOf('"regular",');
  const end = src.indexOf('\n  ],', start);
  if (start < 0 || end < 0) throw new Error(`extract-line-icons: no regular weight in ${component}`);
  const block = src.slice(start, end);
  const elements = [...block.matchAll(/createElement\(\s*"(\w+)"/g)].map((m) => m[1]);
  const paths = [...block.matchAll(/\bd:\s*"([^"]+)"/g)].map((m) => m[1]);
  if (elements.length !== 1 || elements[0] !== 'path' || paths.length !== 1) {
    throw new Error(`extract-line-icons: ${component} is not a single path (${elements.join(',')}); teach the extractor`);
  }
  lines.push(`  ${/^\w+$/.test(name) ? name : JSON.stringify(name)}: ${JSON.stringify(paths[0])},`);
}

const body = `/* GENERATED by tools/design/extract-line-icons.mjs from @phosphor-icons/react (MIT). Do not edit. */
/**
 * The curated line icons of <Icon> (names.ts), regular weight only: one outline per glyph, viewBox 0 0 256 256,
 * drawn with fill = the tone colour. Replaces the icon library at runtime (issue #286: the library shipped six
 * weights per glyph, <Icon> uses one).
 */
import type { LineIconName } from './names';

export const LINE_ICON_VIEWBOX = '0 0 256 256';

export const LINE_ICON_PATHS: Record<LineIconName, string> = {
${lines.join('\n')}
};
`;

if (CHECK) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have !== body) {
    console.error('extract-line-icons: packages/ui/icons/line.ts is stale. Run: node tools/design/extract-line-icons.mjs');
    process.exit(1);
  }
  console.log(`extract-line-icons: ${entries.length} line icons are up to date.`);
} else {
  writeFileSync(OUT, body, 'utf8');
  console.log(`extract-line-icons: wrote ${entries.length} line icons to packages/ui/icons/line.ts`);
}
