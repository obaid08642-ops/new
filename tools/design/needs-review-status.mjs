#!/usr/bin/env node
/**
 * Writes docs/design/NEEDS_REVIEW_STATUS.md from docs/design/needs-review/*.json (owner, 2026-10-14).
 *
 * Every Needs-review line carries `review_status`, one of:
 *   open | open (issue #N)                        not fixed yet
 *   fixed #PR … (issue #N)                        fixed by the named PR(s)
 *   not-a-problem: <one-line reason> (issue #N)   checked, not a defect
 *   owner-decision | owner-decision (issue #N)    waits for the owner
 *   closed-unverified (issue #N: …)               the issue was closed with no linked PR: verify, then set one of the above
 * The PR that fixes a line updates its `review_status` in the same PR, then re-runs this script.
 *
 * Tag of a line: [client] / [backend] / [owner] from its text (the audits write it at the start of `found`, or the
 * journeys files in `tag`), else from `suspect` ("Backend gap" → backend, "Owner decision" → owner,
 * "Client-side" → client), else "untagged".
 *
 *   node tools/design/needs-review-status.mjs           write the report
 *   node tools/design/needs-review-status.mjs --check   fail when a line has no review_status or the report is stale
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '../..');
const DIR = join(REPO, 'docs/design/needs-review');
const OUT = join(REPO, 'docs/design/NEEDS_REVIEW_STATUS.md');
const CHECK = process.argv.includes('--check');

const STATES = ['open', 'fixed', 'not-a-problem', 'owner-decision', 'closed-unverified'];
const stateOf = (s) => {
  const head = String(s || '').split(/[\s:(]/)[0];
  return STATES.includes(head) ? head : null;
};
const tagOf = (e) => {
  const text = [e.tag, e.found, e.problem].filter(Boolean).join(' ');
  const m = /\[(client|backend|owner)\]/.exec(text);
  if (m) return m[1];
  const s = String(e.suspect || '');
  if (/^Backend gap/i.test(s)) return 'backend';
  if (/^Owner decision/i.test(s)) return 'owner';
  if (/^Client-side/i.test(s)) return 'client';
  return 'untagged';
};
const part = (f) => {
  if (f === 'journeys.json') return 'Patient journeys';
  if (f === 'provider-journeys.json') return 'Provider journeys';
  if (f === 'admin-journeys.json') return 'Admin journeys';
  if (f.startsWith('provider-')) return 'Provider app';
  if (f.startsWith('admin-')) return 'Admin';
  if (f.startsWith('final-pass')) return 'Final pass';
  if (/^(batch-|\d)/.test(f)) return 'Patient app and web';
  return 'Other';
};

const problems = [];
const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).sort();
const rows = [];
for (const f of files) {
  const list = JSON.parse(readFileSync(join(DIR, f), 'utf8'));
  list.forEach((e, i) => {
    const state = stateOf(e.review_status);
    if (!state) problems.push(`${f}#${i}: review_status missing or not one of ${STATES.join(' / ')}`);
    rows.push({ f, i, e, state: state ?? 'open', tag: tagOf(e), part: part(f) });
  });
}

const zero = () => Object.fromEntries(STATES.map((s) => [s, 0]));
const count = (key) => {
  const m = new Map();
  for (const r of rows) {
    const k = key(r);
    if (!m.has(k)) m.set(k, zero());
    m.get(k)[r.state]++;
  }
  return m;
};
const table = (title, m) => {
  const L = [`| ${title} | Lines | ${STATES.join(' | ')} |`, `|---|---:|${STATES.map(() => '---:').join('|')}|`];
  const total = zero();
  for (const [k, c] of m) {
    const n = STATES.reduce((a, s) => a + c[s], 0);
    for (const s of STATES) total[s] += c[s];
    L.push(`| ${k} | ${n} | ${STATES.map((s) => c[s]).join(' | ')} |`);
  }
  L.push(`| **Total** | **${rows.length}** | ${STATES.map((s) => `**${total[s]}**`).join(' | ')} |`);
  return L;
};
const esc = (t) => String(t ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (t, n = 220) => { const s = esc(t); return s.length > n ? `${s.slice(0, n - 1)}…` : s; };

const L = [];
L.push('# Needs review: status', '');
L.push('_Generated by `tools/design/needs-review-status.mjs` from `docs/design/needs-review/*.json`. Edit `review_status` in the JSON (in the PR that fixes the line), not this file._', '');
L.push('States: `open` (not fixed yet), `fixed #PR`, `not-a-problem` (with a one-line reason), `owner-decision` (waits for the owner), `closed-unverified` (its GitHub issue was closed with no linked PR; to be verified on main and moved to one of the others).', '');
L.push('## By area', '', ...table('Area', count((r) => r.part)), '');
L.push('## By tag', '', ...table('Tag', count((r) => r.tag)), '');
L.push('## By file', '', ...table('File', count((r) => `\`${r.f}\``)), '');
const owner = rows.filter((r) => r.state === 'owner-decision');
L.push(`## Owner decisions (${owner.length})`, '');
L.push('| # | Where | Screen / element | Question |', '|---:|---|---|---|');
owner.forEach((r, n) => L.push(`| ${n + 1} | \`${r.f}#${r.i}\` ${r.e.file ? `\`${r.e.file}:${r.e.line}\`` : ''} | ${short(`${r.e.screen ?? r.e.scenario ?? ''} ${r.e.element ?? r.e.step ?? ''}`, 80)} | ${short(r.e.found ?? r.e.problem)} |`));
L.push('');
const open = rows.filter((r) => r.state === 'open' || r.state === 'closed-unverified');
L.push(`## Open and unverified (${open.length})`, '');
L.push('| Where | Tag | State | Screen / element | Found |', '|---|---|---|---|---|');
for (const r of open) L.push(`| \`${r.f}#${r.i}\` | ${r.tag} | ${short(r.e.review_status, 60)} | ${short(`${r.e.screen ?? r.e.scenario ?? ''} ${r.e.element ?? r.e.step ?? ''}`, 80)} | ${short(r.e.found ?? r.e.problem, 180)} |`);
L.push('');
const md = L.join('\n');

if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== md) problems.push('docs/design/NEEDS_REVIEW_STATUS.md is stale: run node tools/design/needs-review-status.mjs');
} else {
  writeFileSync(OUT, md);
}
if (problems.length) { for (const p of problems) console.error(`needs-review-status: ${p}`); process.exit(1); }
const total = zero(); for (const r of rows) total[r.state]++;
console.log(`needs-review-status: ${rows.length} lines: ${STATES.map((s) => `${total[s]} ${s}`).join(', ')}${CHECK ? ' (check ok)' : ' written'}`);
