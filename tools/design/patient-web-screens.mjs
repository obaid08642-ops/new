#!/usr/bin/env node
/**
 * docs/qa/patient-web-screens.md: one row per patient-web route (element | wired to | status), generated from
 * docs/design/inventory/screens.json (run tools/design/screen-inventory.mjs first), static-screens.json.
 * Open Needs-review lines per screen are in docs/design/NEEDS_REVIEW_STATUS.md. Static analysis only: it says what each route calls and whether the
 * call reaches a backend handler; it does not click anything.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const routes = read('docs/design/inventory/screens.json').routes.filter((r) => r.app === 'patient-web');
const statics = read('docs/design/inventory/static-screens.json');
const tally = {};
const bump = (k) => (tally[k] = (tally[k] ?? 0) + 1);
const groups = new Map();
for (const r of routes) {
  const g = '/' + (r.route.split('/')[1] ?? '');
  (groups.get(g) ?? groups.set(g, []).get(g)).push(r);
}
let body = '';
for (const [g, list] of [...groups].sort()) {
  body += `\n## ${g} (${list.length})\n\n| Route | Element | Wired to | Status |\n|---|---|---|---|\n`;
  for (const r of list.sort((a, b) => a.route.localeCompare(b.route))) {
    if (!r.calls.length) {
      const s = statics[r.route];
      const status = s ? `static (${s.verdict})` : r.redirect ? 'redirect' : 'no API call, not classified';
      bump(status.startsWith('static') ? 'static' : r.redirect ? 'redirect' : 'unclassified');
      body += `| \`${r.route}\` | page | ${r.redirect ? `redirect to \`${r.redirect}\`` : s ? s.reason.replace(/\|/g, '/').slice(0, 140) : '-'} | ${status} |\n`;
      continue;
    }
    for (const c of r.calls) {
      bump(c.status);
      body += `| \`${r.route}\` | \`${c.method} ${c.path}\` (${c.file.replace('patient-web/', '')}:${c.line}) | ${c.backend ? '`' + c.backend.replace('backend/src/', '') + '`' : c.target} | ${c.status} |\n`;
    }
  }
}
const calls = Object.entries(tally).filter(([k]) => !['static', 'redirect', 'unclassified'].includes(k));
const head = `# Patient web screens: element | wired to | status

Generated by \`node tools/design/patient-web-screens.mjs\` from \`docs/design/inventory/screens.json\` (commit ${read('docs/design/inventory/screens.json').commit}). **Static analysis, not a click-through:** it lists every route and each API call its code makes, and whether that call reaches a backend handler (through the BFF route or the \`/api/patient\` proxy allowlist). It does not run the screens.

## Counts

- Routes: ${routes.length}; with API calls: ${routes.filter((r) => r.calls.length).length}; static (no call): ${tally.static ?? 0}; redirects: ${tally.redirect ?? 0}; no call and not classified: ${tally.unclassified ?? 0}.
- Calls: ${calls.reduce((n, [, v]) => n + v, 0)} (${calls.map(([k, v]) => `${k} ${v}`).join(', ')}).

Status: OK = the call reaches a backend handler with the right method; PROXY_BLOCKED? = the proxy allowlist could not be proven for the sample values (checked by hand where listed in the PR); PARTIAL = the path ends in a variable, only the prefix is checked; static = the page has no call by design (reason shown).
`;
writeFileSync('docs/qa/patient-web-screens.md', head + body);
console.log(head.split('\n').filter((l) => l.startsWith('- ')).join('\n'));
